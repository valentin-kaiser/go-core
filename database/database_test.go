func TestDatabase_MultipleOnConnectHandlers(t *testing.T) {
	db := database.New[TestQueries](database.DriverSQLite, "test-multi-handlers")

	var handler1Called atomic.Bool
	var handler2Called atomic.Bool

	db.RegisterOnConnectHandler(func(_ *sql.DB) error {
		handler1Called.Store(true)
		return nil
	})

	db.RegisterOnConnectHandler(func(_ *sql.DB) error {
		handler2Called.Store(true)
		return nil
	})

	dsn := memoryDSN

	db.Connect(connectInterval, dsn)
	cleanupDisconnect(t, db)
	db.AwaitConnection()

	if !handler1Called.Load() {
		t.Error("First handler should have been called")
	}
	if !handler2Called.Load() {
		t.Error("Second handler should have been called")
	}
}

func cleanupDisconnect(tb testing.TB, db interface{ Disconnect() error }) {
	tb.Helper()
	tb.Cleanup(func() { disconnect(tb, db) })
}

func awaitConnected(tb testing.TB, db interface{ Connected() bool }) {
	tb.Helper()
	await.Until(tb, connectTimeout, db.Connected, "the database to connect")
}

func disconnect(tb testing.TB, db interface{ Disconnect() error }) {
	tb.Helper()
	err := db.Disconnect()
	if err != nil {
		tb.Errorf("disconnecting database failed: %v", err)
	}
}
